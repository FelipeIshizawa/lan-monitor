CREATE TABLE latency_rollups_1m (
 device_id BIGINT UNSIGNED NOT NULL,
 bucket_at DATETIME NOT NULL,
 probe_kind VARCHAR(4) NOT NULL,
 sample_count INT UNSIGNED NOT NULL,
 success_count INT UNSIGNED NOT NULL,
 latency_sum_us BIGINT UNSIGNED NOT NULL,
 latency_min_us INT UNSIGNED,
 latency_max_us INT UNSIGNED,
 PRIMARY KEY(device_id,bucket_at,probe_kind)
) ENGINE=InnoDB
PARTITION BY RANGE COLUMNS(bucket_at) (
 PARTITION p_before_202610 VALUES LESS THAN ('2026-10-01'),
 PARTITION p202610 VALUES LESS THAN ('2026-11-01'),
 PARTITION p202611 VALUES LESS THAN ('2026-12-01'),
 PARTITION p_future VALUES LESS THAN (MAXVALUE)
);
